/* --- The stamp ------------------------------------------------------------ */

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex')
const source = sha256(
  JSON.stringify([
    ...PNGS.map((png) => [png.file, png.width, png.height, png.html()]),
    [ICO.file, ICO.sizes, iconPage(false)],
  ])
)

/** Width and height from a PNG's IHDR, which is always the first chunk. */
function pngSize(bytes) {
  return { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) }
}

/**
 * An ICO holding PNGs. Every browser that still asks for favicon.ico reads
 * PNG entries, and it keeps this to a header and a directory rather than a
 * bitmap encoder.
 */
function ico(images) {
  const header = Buffer.alloc(6 + 16 * images.length)
  header.writeUInt16LE(0, 0)
  header.writeUInt16LE(1, 2)
  header.writeUInt16LE(images.length, 4)
  let offset = header.length
  images.forEach(({ size, bytes }, i) => {
    const at = 6 + 16 * i
    header.writeUInt8(size >= 256 ? 0 : size, at)
    header.writeUInt8(size >= 256 ? 0 : size, at + 1)
    header.writeUInt16LE(1, at + 4)
    header.writeUInt16LE(32, at + 6)
    header.writeUInt32LE(bytes.length, at + 8)
    header.writeUInt32LE(offset, at + 12)
    offset += bytes.length
  })
  return Buffer.concat([header, ...images.map((image) => image.bytes)])
}

/* --- --check -------------------------------------------------------------- */

function runCheck() {
  const problems = []
  const rel = (path) => relative(ROOT, path)

  if (!existsSync(ICON_SVG) || readFileSync(ICON_SVG, 'utf8') !== iconSvg) {
    problems.push(`${rel(ICON_SVG)} is not what apps/web/lib/mark.ts draws`)
  }

  const stamp = existsSync(STAMP) ? JSON.parse(readFileSync(STAMP, 'utf8')) : null
  if (stamp === null) {
    problems.push(`${rel(STAMP)} is missing, so nothing records what the images were drawn from`)
  } else {
    if (stamp.source !== source) {
      problems.push(
        `the mark, the site's tokens or the card layout changed after the images were rendered ` +
          `(rendered from ${String(stamp.source).slice(0, 16)}, source is now ${source.slice(0, 16)})`
      )
    }
    for (const item of [...PNGS, { file: ICO.file }]) {
      const path = join(WEB, item.file)
      if (!existsSync(path)) {
        problems.push(`apps/web/${item.file} is missing`)
        continue
      }
      const bytes = readFileSync(path)
      if (stamp.files?.[item.file] !== sha256(bytes)) {
        problems.push(`apps/web/${item.file} is not the file that was rendered`)
      }
      if ('width' in item) {
        const got = pngSize(bytes)
        if (got.width !== item.width || got.height !== item.height) {
          problems.push(
            `apps/web/${item.file} is ${String(got.width)}x${String(got.height)}, ` +
              `the metadata says ${String(item.width)}x${String(item.height)}`
          )
        }
      }
    }
  }

  if (problems.length > 0) {
    console.error('gen-brand: the committed icons and social card are stale.\n')
    for (const problem of problems) console.error(`  ${problem}`)
    console.error('\n  Regenerate with "make brand" and look at the images before committing.\n')
    process.exit(1)
  }
  console.log(
    `gen-brand: icon.svg matches the mark, and ${String(PNGS.length + 1)} raster images were ` +
      `rendered from this exact source (${source.slice(0, 16)}). Pixels are not re-rendered ` +
      `here: see the header of tools/gen-brand.mjs.`
  )
}

/* --- Rendering ------------------------------------------------------------ */

const seq = { id: 0 }
function cdp(ws, method, params = {}) {
  return new Promise((resolve, reject) => {
    const id = (seq.id += 1)
    const onMessage = (event) => {
      const msg = JSON.parse(event.data)
      if (msg.id !== id) return
      ws.removeEventListener('message', onMessage)
      if (msg.error) reject(new Error(`${method}: ${msg.error.message}`))
      else resolve(msg.result)
    }
    ws.addEventListener('message', onMessage)
    ws.send(JSON.stringify({ id, method, params }))
  })
}

async function render() {
  const debug = await freePort()
  const chrome = spawn(
    chromeBinary('gen-brand'),
    [
      '--headless',
      '--disable-gpu',
      '--no-sandbox',
      '--disable-dev-shm-usage',
      '--hide-scrollbars',
      `--remote-debugging-port=${String(debug)}`,
      chromeProfile('gen-brand'),
      'about:blank',
    ],
    { stdio: ['ignore', 'pipe', 'pipe'] }
  )
  const browser = new WebSocket(await waitForDebugEndpoint(chrome, debug))
  await new Promise((r) => browser.addEventListener('open', r, { once: true }))
  const { targetId } = await cdp(browser, 'Target.createTarget', { url: 'about:blank' })
  const targets = await (await fetch(`http://127.0.0.1:${String(debug)}/json/list`)).json()
  const page = new WebSocket(targets.find((t) => t.id === targetId).webSocketDebuggerUrl)
  await new Promise((r) => page.addEventListener('open', r, { once: true }))
  await cdp(page, 'Page.enable')
  // Transparent, so the favicon's rounded corners are corners and not ink.
  await cdp(page, 'Emulation.setDefaultBackgroundColorOverride', {
    color: { r: 0, g: 0, b: 0, a: 0 },
  })

  async function shoot(html, width, height) {
    await cdp(page, 'Emulation.setDeviceMetricsOverride', {
      width,
      height,
      deviceScaleFactor: 1,
      mobile: false,
    })
    const loaded = new Promise((resolve) => {
      const onMessage = (event) => {
        if (JSON.parse(event.data).method !== 'Page.loadEventFired') return
        page.removeEventListener('message', onMessage)
        resolve()
      }
      page.addEventListener('message', onMessage)
    })
    await cdp(page, 'Page.navigate', {
      url: `data:text/html;base64,${Buffer.from(html).toString('base64')}`,
    })
    await loaded
    // Load fires before system fonts are guaranteed to be laid out.
    await cdp(page, 'Runtime.evaluate', { expression: 'document.fonts.ready', awaitPromise: true })
    const shot = await cdp(page, 'Page.captureScreenshot', {
      format: 'png',
      clip: { x: 0, y: 0, width, height, scale: 1 },
    })
    return Buffer.from(shot.data, 'base64')
  }

  const files = {}
  const write = (file, bytes) => {
    const path = join(WEB, file)
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, bytes)
    files[file] = sha256(bytes)
  }

  try {
    for (const png of PNGS) write(png.file, await shoot(png.html(), png.width, png.height))
    const entries = []
    for (const size of ICO.sizes)
      entries.push({ size, bytes: await shoot(iconPage(false), size, size) })
    write(ICO.file, ico(entries))
  } finally {
    page.close()
    browser.close()
    reap(chrome)
  }

  writeFileSync(ICON_SVG, iconSvg)
  mkdirSync(dirname(STAMP), { recursive: true })
  writeFileSync(
    STAMP,
    `${JSON.stringify({ source, platform: `${process.platform}-${process.arch}`, files }, null, 2)}\n`
  )
  console.log(
    `gen-brand: wrote app/icon.svg, ${Object.keys(files).join(', ')} under apps/web from ${source.slice(0, 16)}`
  )
}

if (check) {
  runCheck()
  finish(0)
} else {
  render()
    .then(() => finish(0))
    .catch((err) => {
      console.error(`gen-brand: ${err.message}`)
      finish(1)
    })
}
